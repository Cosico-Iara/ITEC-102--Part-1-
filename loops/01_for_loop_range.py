# 1. For Loop with range(start, stop)
# Used to repeat a block of code a specific number of times.
# range(start, stop) – Counts from start up to stop - 1. The stop value is NOT included.

# Code_Example:
print("Numbers 1 to 10:")
for number in range(1, 11):  # stop value (11) is NOT included
    print(number)
    